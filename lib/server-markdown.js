import fs from 'fs/promises';
import path from 'path';

const SUBMISSIONS_DIR = path.join(process.cwd(), 'submissions');

/**
 * Ensure the submissions directory exists on disk.
 */
async function ensureDir() {
  try {
    await fs.mkdir(SUBMISSIONS_DIR, { recursive: true });
  } catch (err) {
    console.error('Error ensuring submissions directory:', err);
  }
}

/**
 * Serializes submission data into standard GitHub-flavored Markdown with frontmatter.
 */
export function serializeMarkdown({
  id,
  date = new Date().toISOString(),
  status = 'New',
  name = '',
  phone = '',
  email = '',
  topic = 'General Enquiry',
  urgency = 'Normal',
  message = '',
  notes = '',
}) {
  const safeName = String(name || '').replace(/["\n\r]/g, ' ');
  const safeEmail = String(email || '').replace(/["\n\r]/g, ' ');
  const safePhone = String(phone || '').replace(/["\n\r]/g, ' ');
  const safeTopic = String(topic || '').replace(/["\n\r]/g, ' ');
  const safeUrgency = String(urgency || 'Normal').replace(/["\n\r]/g, ' ');

  return `---
id: "${id}"
date: "${date}"
status: "${status}"
name: "${safeName}"
email: "${safeEmail}"
phone: "${safePhone}"
topic: "${safeTopic}"
urgency: "${safeUrgency}"
---

# Investigation Case File: ${id}

> **Official Record**: Eaglesight Detective & Forensic Services Inquiry Registry  
> **Classification**: Confidential / Investigative Privilege  
> **Status**: **${status.toUpperCase()}**

---

## 1. Client Information
- **Client Name**: ${safeName}
- **Email Address**: ${safeEmail || 'Not provided'}
- **Contact Phone**: ${safePhone || 'Not provided'}
- **Date Received**: ${new Date(date).toLocaleString('en-US', { timeZone: 'UTC', dateStyle: 'full', timeStyle: 'medium' })} (UTC)
- **Assigned Urgency**: ${safeUrgency}

---

## 2. Service Requested
- **Service Domain**: ${safeTopic}

---

## 3. Client Case Brief / Message
${message ? message.trim() : '_No client statement provided._'}

---

## 4. Investigator Case Notes
${notes ? notes.trim() : '_No internal investigator notes recorded._'}

---
*Generated by Eaglesight Secure Records System (ISO/IEC 27001:2022 Compliant)*
`;
}

/**
 * Parses frontmatter and body from a .md file string.
 */
export function parseMarkdown(content) {
  const frontmatterRegex = /^---\r?\n([\s\S]*?)\r?\n---\r?\n([\s\S]*)$/;
  const match = content.match(frontmatterRegex);

  const meta = {
    id: '',
    date: new Date().toISOString(),
    status: 'New',
    name: '',
    email: '',
    phone: '',
    topic: 'General Enquiry',
    urgency: 'Normal',
  };

  let body = content;

  if (match) {
    const yamlBlock = match[1];
    body = match[2];

    yamlBlock.split(/\r?\n/).forEach((line) => {
      const parts = line.split(':');
      if (parts.length >= 2) {
        const key = parts[0].trim();
        let val = parts.slice(1).join(':').trim();
        if (val.startsWith('"') && val.endsWith('"')) {
          val = val.substring(1, val.length - 1);
        }
        meta[key] = val;
      }
    });
  }

  // Extract client message
  let message = '';
  const messageMatch = body.match(/## 3\. Client Case Brief \/ Message\r?\n([\s\S]*?)(?=\r?\n---\r?\n## 4\.|$)/);
  if (messageMatch) {
    message = messageMatch[1].trim();
  }

  // Extract notes
  let notes = '';
  const notesMatch = body.match(/## 4\. Investigator Case Notes\r?\n([\s\S]*?)(?=\r?\n---|$)/);
  if (notesMatch) {
    notes = notesMatch[1].trim();
    if (notes.startsWith('_No internal investigator notes')) {
      notes = '';
    }
  }

  return {
    ...meta,
    message,
    notes,
    rawMarkdown: content,
  };
}

/**
 * Creates and writes a new .md submission file to the submissions/ folder.
 */
export async function createSubmissionFile(data) {
  await ensureDir();

  const id = `ENQ-${new Date().getFullYear()}-${Math.floor(1000 + Math.random() * 9000)}`;
  const date = new Date().toISOString();

  const mdContent = serializeMarkdown({
    id,
    date,
    status: 'New',
    name: data.name,
    phone: data.phone,
    email: data.email,
    topic: data.topic,
    urgency: data.urgency || 'Normal',
    message: data.message,
    notes: '',
  });

  const filePath = path.join(SUBMISSIONS_DIR, `${id}.md`);
  await fs.writeFile(filePath, mdContent, 'utf-8');

  // Also commit to GitHub if GITHUB_TOKEN and GITHUB_REPO are set in environment
  if (process.env.GITHUB_TOKEN && process.env.GITHUB_REPO) {
    try {
      await pushToGitHub(`submissions/${id}.md`, mdContent, `Add inquiry record ${id}`);
    } catch (err) {
      console.warn('GitHub API sync warning (local file saved successfully):', err.message);
    }
  }

  return {
    id,
    date,
    status: 'New',
    ...data,
    notes: '',
    rawMarkdown: mdContent,
  };
}

/**
 * Reads all .md submission files from the submissions/ directory.
 */
export async function getAllSubmissions() {
  await ensureDir();

  try {
    const files = await fs.readdir(SUBMISSIONS_DIR);
    const mdFiles = files.filter((f) => f.endsWith('.md'));

    const items = await Promise.all(
      mdFiles.map(async (file) => {
        try {
          const content = await fs.readFile(path.join(SUBMISSIONS_DIR, file), 'utf-8');
          return parseMarkdown(content);
        } catch {
          return null;
        }
      })
    );

    return items
      .filter(Boolean)
      .sort((a, b) => new Date(b.date || 0) - new Date(a.date || 0));
  } catch (err) {
    console.error('Failed to read submissions:', err);
    return [];
  }
}

/**
 * Updates status or notes in an existing .md file.
 */
export async function updateSubmission(id, updates) {
  await ensureDir();
  const filePath = path.join(SUBMISSIONS_DIR, `${id}.md`);

  try {
    const content = await fs.readFile(filePath, 'utf-8');
    const existing = parseMarkdown(content);

    const updatedData = {
      ...existing,
      ...updates,
      id,
    };

    const newMd = serializeMarkdown(updatedData);
    await fs.writeFile(filePath, newMd, 'utf-8');

    if (process.env.GITHUB_TOKEN && process.env.GITHUB_REPO) {
      try {
        await pushToGitHub(`submissions/${id}.md`, newMd, `Update inquiry record ${id}`);
      } catch (err) {
        console.warn('GitHub API sync warning:', err.message);
      }
    }

    return parseMarkdown(newMd);
  } catch (err) {
    console.error(`Failed to update ${id}:`, err);
    throw new Error(`Submission ${id} not found.`);
  }
}

/**
 * Deletes a .md file.
 */
export async function deleteSubmission(id) {
  await ensureDir();
  const filePath = path.join(SUBMISSIONS_DIR, `${id}.md`);

  try {
    await fs.unlink(filePath);
    return true;
  } catch (err) {
    console.error(`Failed to delete ${id}:`, err);
    return false;
  }
}

/**
 * GitHub API helper to commit files directly into the repository (for serverless environments)
 */
async function pushToGitHub(repoPath, content, commitMessage) {
  const token = process.env.GITHUB_TOKEN;
  const repo = process.env.GITHUB_REPO; // e.g. "owner/repo"
  if (!token || !repo) return;

  const url = `https://api.github.com/repos/${repo}/contents/${repoPath}`;
  const base64Content = Buffer.from(content).toString('base64');

  // Check if file already exists to get SHA
  let sha;
  try {
    const getRes = await fetch(url, {
      headers: {
        Authorization: `Bearer ${token}`,
        'User-Agent': 'Eaglesight-App',
      },
    });
    if (getRes.ok) {
      const data = await getRes.json();
      sha = data.sha;
    }
  } catch {
    // New file
  }

  await fetch(url, {
    method: 'PUT',
    headers: {
      Authorization: `Bearer ${token}`,
      'User-Agent': 'Eaglesight-App',
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      message: commitMessage,
      content: base64Content,
      sha: sha || undefined,
    }),
  });
}

